export const FONTS = { 7: GLYPHS7, 5: GLYPHS5, 3: GLYPHS3 };
const FALLBACK = { 'Ä': 'A', 'Ö': 'O', 'Å': 'A' }; // for fonts too small for the dots

// Text → glyph keys. Letters are uppercase, except an 'i' right after a digit (the imaginary unit, "0.12i").
// '−' (minus sign) and 'x' between digits (zoom) map to their glyphs; unknown characters become spaces.
function glyphKeys(text, font) {
  const out = [];
  const chars = [...text];
  chars.forEach((c, k) => {
    const prev = chars[k - 1] || '';
    if (c === 'i' && /[0-9]/.test(prev)) return out.push('i');
    if (c === '−' || c === '–') return out.push('-');
    let u = c.toUpperCase();
    if (!font[u] && FALLBACK[u]) u = FALLBACK[u];
    out.push(font[u] ? u : ' ');
  });
  return out;
}

// Text → bitmap { w, h, bits } (1 = stitch) in the font `height` tall (7, 5 or 3), glyphs one column apart.
export function textBitmap(text, height = 7) {
  const font = FONTS[height] || GLYPHS7;
  const h = font['0'].length;
  const keys = glyphKeys(text, font);
  const w = Math.max(0, keys.reduce((s, k) => s + font[k][0].length + 1, 0) - 1);
  const bits = new Uint8Array(w * h);
  let x = 0;
  for (const k of keys) {
    const g = font[k];
    for (let y = 0; y < h; y++) for (let c = 0; c < g[y].length; c++) if (g[y][c] === '#') bits[y * w + x + c] = 1;
    x += g[0].length + 1;
  }
  return { w, h, bits };
}

// Default label: center and zoom with just enough digits to find the spot again (more for deeper zooms).
export function coordinateLabel({ cx, cy, w, rot }) {
  const d = Math.min(16, Math.max(3, Math.ceil(-Math.log10(w)) + 3));
  const zoom = 3.4 / w;
  const z = zoom < 1e5 ? zoom.toFixed(zoom < 100 ? 1 : 0) : zoom.toExponential(2).replace('e+', 'E');
  const deg = Math.round(((rot || 0) * 180) / Math.PI);
  return `${cx.toFixed(d)} ${cy < 0 ? '-' : '+'} ${Math.abs(cy).toFixed(d)}i  ×${z}${deg ? `  ${deg}°` : ''}`;
}

// Stamp a label into `indices` (W × H thread indices, row-major), in place.
// opts: { text, font: 7 | 5 | 3 (rows), pos: 'bl' | 'bc' | 'br', size: 1…3, margin (stitches), fg, bg (thread indices), bgMode: 'none' |
// 'outline' | 'band' }. Shrinks the size if the text doesn't fit the width; clips what still doesn't.
// Returns { x, y, w, h, size, clipped } of the stamped box (stitch coordinates), or null if there is nothing to stamp.
export function stampLabel(indices, W, H, { text, font = 7, pos = 'br', size = 1, margin = 5, fg, bg, bgMode = 'outline' }) {
  const bmp = textBitmap(text || '', font);
  if (!bmp.w) return null;
  const pad = bgMode === 'none' ? 0 : 1;
  let s = size;
  while (s > 1 && bmp.w * s + 2 * (margin + pad) > W) s--;
  const bw = bmp.w * s, bh = bmp.h * s;
  const x0 = pos === 'bl' ? margin + pad : pos === 'bc' ? Math.round((W - bw) / 2) : W - margin - pad - bw;
  const y0 = H - margin - pad - bh;
  const on = (x, y) => {
    const gx = Math.floor((x - x0) / s), gy = Math.floor((y - y0) / s);
    return x >= x0 && y >= y0 && gx < bmp.w && gy < bmp.h && bmp.bits[gy * bmp.w + gx] === 1;
  };
  const put = (x, y, t) => { if (x >= 0 && y >= 0 && x < W && y < H) indices[y * W + x] = t; };
  if (bgMode === 'band') {
    for (let y = y0 - pad; y < y0 + bh + pad; y++) for (let x = x0 - pad; x < x0 + bw + pad; x++) put(x, y, bg);
  } else if (bgMode === 'outline') {
    // 1-stitch halo around the text (8 neighbours), so it reads on any background.
    for (let y = y0 - 1; y <= y0 + bh; y++) for (let x = x0 - 1; x <= x0 + bw; x++) {
      if (on(x, y)) continue;
      let near = false;
      for (let dy = -1; dy <= 1 && !near; dy++) for (let dx = -1; dx <= 1; dx++) if (on(x + dx, y + dy)) { near = true; break; }
      if (near) put(x, y, bg);
    }
  }
  for (let y = y0; y < y0 + bh; y++) for (let x = x0; x < x0 + bw; x++) if (on(x, y)) put(x, y, fg);
  return { x: x0, y: y0, w: bw, h: bh, size: s, clipped: x0 < 0 || x0 + bw > W || y0 < 0 };
}
